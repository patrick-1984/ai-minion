#!/usr/bin/env python3
"""Turn the Go repository's golden vectors into a C header for the thin Worker tests.

Usage: gen_vectors.py REPO_ROOT OUT_HEADER

Sources: internal/identity/testdata/hub_cert_vectors.json, internal/identity/testdata/vectors.json,
internal/transport/testdata/handshake_vectors.json. The thin Worker accepts certificates valid up to 3650 days
(Hub PR #24); a vector that expects cert_malformed only because it exceeds 400 days is therefore expected to pass
the structural check here (it is listed in OVERRIDES).
"""

import base64
import json
import sys

OVERRIDES = {"validity_400d_plus_1ms": "ok"}


def b64d(s):
    return base64.urlsafe_b64decode(s + "=" * (-len(s) % 4))


def carr(b):
    return "{" + ",".join(str(x) for x in b) + "}" if b else "{0}"


def cstr(s):
    return json.dumps(s)  # a JSON string literal is a valid C string literal for ASCII input


def main():
    root, out = sys.argv[1], sys.argv[2]
    certs = json.load(open(f"{root}/internal/identity/testdata/hub_cert_vectors.json"))
    ident = json.load(open(f"{root}/internal/identity/testdata/vectors.json"))
    hs = json.load(open(f"{root}/internal/transport/testdata/handshake_vectors.json"))
    L = ["/* generated by gen_vectors.py from the Go repository; do not edit */", "#include <stdint.h>",
         "#include <stddef.h>"]

    L.append("typedef struct { const char *name; const char *expect; int has_now; int64_t now_ms; "
             "uint8_t root_seed[32]; const char *cert_b64; uint8_t sha[32]; } cert_vec;")
    L.append("static const cert_vec CERT_VECS[] = {")
    for v in certs:
        exp = OVERRIDES.get(v["name"], v["expect"])
        has_now = v.get("now_ms") is not None
        L.append("  {%s, %s, %d, %dLL, %s, %s, %s}," % (
            cstr(v["name"]), cstr(exp), int(has_now), int(v["now_ms"]) if has_now else 0,
            carr(bytes.fromhex(v["root_seed_hex"])), cstr(v["cert_b64url"]), carr(bytes.fromhex(v["cert_sha256_hex"]))))
    L.append("};")

    L.append("typedef struct { const char *purpose; uint8_t data[160]; size_t len; uint8_t sig[64]; } sig_vec;")
    L.append("typedef struct { const char *name; uint8_t seed[32]; uint8_t pub[32]; const char *fp; "
             "size_t nsig; sig_vec sigs[8]; } key_vec;")
    L.append("static const key_vec KEY_VECS[] = {")
    for k in ident["keys"]:
        sigs = []
        for s in k["signatures"][:8]:
            d = b64d(s["data_b64"])
            sigs.append("{%s, %s, %d, %s}" % (cstr(s["purpose"]), carr(d), len(d), carr(b64d(s["sig_b64"]))))
        L.append("  {%s, %s, %s, %s, %d, {%s}}," % (cstr(k["name"]), carr(b64d(k["seed_b64"])), carr(b64d(k["pub_b64"])),
                                                  cstr(k["fingerprint"]), len(sigs), ",".join(sigs)))
    L.append("};")
    t = ident["transition"]
    L.append("static const struct { uint64_t seq; uint8_t old_pub[32], new_pub[32]; const char *created; "
             "uint8_t sig[64]; } TRANSITION = {%dULL, %s, %s, %s, %s};" % (
                 t["seq"], carr(b64d(t["old_pub"])), carr(b64d(t["new_pub"])), cstr(t["created_at"]),
                 carr(b64d(t["sig_by_old"]))))

    L.append("typedef struct { const char *name; const char *wh; const char *hh; uint8_t hash[32]; } tr_vec;")
    L.append("static const tr_vec TR_VECS[] = {")
    for v in hs["transcript"]:
        L.append("  {%s, %s, %s, %s}," % (cstr(v["name"]), cstr(v["worker_hello"]), cstr(v["hub_hello"]),
                                         carr(bytes.fromhex(v["hash"]))))
    L.append("};")
    L.append("typedef struct { const char *name; uint8_t ew[32], eh[32], ewp[32], ehp[32], dh[32]; "
             "uint8_t isk[64]; size_t isk_len; uint8_t th[32], w2h[32], h2w[32]; } kdf_vec;")
    L.append("static const kdf_vec KDF_VECS[] = {")
    for v in hs["kdf"]:
        isk = bytes.fromhex(v.get("isk") or "")
        L.append("  {%s, %s, %s, %s, %s, %s, %s, %d, %s, %s, %s}," % (
            cstr(v["name"]), carr(bytes.fromhex(v["eph_w_priv"])), carr(bytes.fromhex(v["eph_h_priv"])),
            carr(bytes.fromhex(v["eph_w_pub"])), carr(bytes.fromhex(v["eph_h_pub"])), carr(bytes.fromhex(v["dh"])),
            carr(isk), len(isk), carr(bytes.fromhex(v["transcript_hash"])), carr(bytes.fromhex(v["worker_to_hub"])),
            carr(bytes.fromhex(v["hub_to_worker"]))))
    L.append("};")
    L.append("typedef struct { uint8_t key[32]; uint64_t counter; uint8_t plain[1024]; size_t plen; "
             "uint8_t wire[1100]; size_t wlen; } rec_vec;")
    L.append("static const rec_vec REC_VECS[] = {")
    for v in hs["records"]:
        p, w = bytes.fromhex(v["plaintext"]), bytes.fromhex(v["wire"])
        L.append("  {%s, %dULL, %s, %d, %s, %d}," % (carr(bytes.fromhex(v["key"])), int(v["counter"]), carr(p), len(p),
                                                   carr(w), len(w)))
    L.append("};")
    L.append("#define NELEM(a) (sizeof(a) / sizeof((a)[0]))")
    open(out, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
