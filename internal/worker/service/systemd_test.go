func TestWriteIfChangedIsAtomicAndIdempotent(t *testing.T) {
	p := filepath.Join(t.TempDir(), "a", "b.service")
	if err := writeIfChanged(p, "x", 0o755, 0o644); err != nil {
		t.Fatal(err)
	}
	st1, _ := os.Stat(p)
	if st1.Mode().Perm() != 0o644 {
		t.Errorf("mode = %v", st1.Mode())
	}
	if err := writeIfChanged(p, "x", 0o755, 0o644); err != nil {
		t.Fatal(err)
	}
	if err := writeIfChanged(p, "y", 0o755, 0o644); err != nil {
		t.Fatal(err)
	}
	if data, _ := os.ReadFile(p); string(data) != "y" {
		t.Errorf("content = %q", data)
	}
	entries, _ := os.ReadDir(filepath.Dir(p))
	if len(entries) != 1 {
		t.Errorf("temporary files left behind: %v", entries)
	}
}
