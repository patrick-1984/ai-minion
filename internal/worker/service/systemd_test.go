// A unit that an earlier "worker up" wrote to /etc overrides the packaged one,
// so it must go when the packaged unit is the wanted content.
func TestInstallSystemdRemovesAStaleEtcUnitThatShadowsTheIdenticalPackagedUnit(t *testing.T) {
	r := &fakeRunner{answer: activeAnswers("active")}
	d := testDeps(t, r)
	_ = os.MkdirAll(d.PackagedUnitDirs[0], 0o755)
	_ = os.MkdirAll(d.SystemUnitDir, 0o755)
	unit, _ := SystemUnit(DefaultBinary)
	packaged := filepath.Join(d.PackagedUnitDirs[0], TemplateUnitName)
	_ = os.WriteFile(packaged, []byte(unit), 0o644)
	stale := strings.Replace(unit, "ExecStart="+DefaultBinary, "ExecStart=/usr/local/bin/minion", 1)
	etc := filepath.Join(d.SystemUnitDir, TemplateUnitName)
	if err := os.WriteFile(etc, []byte(stale), 0o644); err != nil {
		t.Fatal(err)
	}
	res, err := Install(context.Background(), d, systemReq("ann"), nil)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := os.Stat(etc); err == nil {
		t.Error("the stale /etc unit still overrides the packaged unit")
	}
	if res.Path != packaged {
		t.Errorf("path = %q", res.Path)
	}
}

// Two users with different binaries: the second install must not change the
// executable of the first one's service.
func TestInstallSystemdTwoUsersKeepTheirOwnBinary(t *testing.T) {
	r := &fakeRunner{answer: activeAnswers("active")}
	d := testDeps(t, r)
	ann, bob := systemReq("ann"), systemReq("bob")
	ann.Binary, bob.Binary = "/home/ann/bin/minion", "/home/bob/bin/minion"
	for _, req := range []Request{ann, bob} {
		if _, err := Install(context.Background(), d, req, nil); err != nil {
			t.Fatal(err)
		}
	}
	read := func(p ...string) string {
		b, err := os.ReadFile(filepath.Join(append([]string{d.SystemUnitDir}, p...)...))
		if err != nil {
			t.Fatal(err)
		}
		return string(b)
	}
	if got := read(TemplateUnitName); strings.Contains(got, "/home/") {
		t.Errorf("the shared template names a user's binary:\n%s", got)
	}
	if got := read("minion-worker@ann.service.d", dropInName); !strings.Contains(got, "/home/ann/bin/minion") || strings.Contains(got, "bob") {
		t.Errorf("ann's drop-in:\n%s", got)
	}
	if got := read("minion-worker@bob.service.d", dropInName); !strings.Contains(got, "/home/bob/bin/minion") {
		t.Errorf("bob's drop-in:\n%s", got)
	}
}

