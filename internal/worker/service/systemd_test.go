func lingerAnswers(before, after string) (*fakeRunner, *int) {
	enabled := 0
	r := &fakeRunner{}
	r.answer = func(line string) (string, error) {
		switch {
		case strings.Contains(line, "is-active"):
			return "active\n", nil
		case strings.HasPrefix(line, "loginctl enable-linger"):
			enabled++
			return "", nil
		case strings.HasPrefix(line, "loginctl show-user"):
			if enabled == 0 {
				return "Linger=" + before + "\n", nil
			}
			return "Linger=" + after + "\n", nil
		}
		return "", nil
	}
	return r, &enabled
}

func TestInstallSystemdUserUnitWithLingerAlreadyOn(t *testing.T) {
	r, enabled := lingerAnswers("yes", "yes")
	home := t.TempDir()
	res, err := Install(context.Background(), testDeps(t, r), userReq(home), nil)
	if err != nil {
		t.Fatal(err)
	}
	unitPath := filepath.Join(home, ".config", "systemd", "user", UserUnitName)
	if res.Path != unitPath || res.Scope != ScopeUser {
		t.Errorf("result = %+v", res)
	}
	if _, err := os.Stat(unitPath); err != nil {
		t.Fatal(err)
	}
	if *enabled != 0 {
		t.Error("enable-linger ran although lingering was on")
	}
	for _, want := range []string{"systemctl --user daemon-reload", "systemctl --user enable minion-worker.service", "systemctl --user restart minion-worker.service"} {
		found := false
		for _, l := range r.lines() {
			found = found || l == want
		}
		if !found {
			t.Errorf("missing command %q in %v", want, r.lines())
		}
	}
}

