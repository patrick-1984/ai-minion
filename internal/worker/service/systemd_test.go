const deployUnit = "../../../deploy/systemd/minion-worker@.service"

// TestSystemUnitIsIdenticalToTheShippedUnit is the AC: the unit "worker up"
// installs is exactly the unit the packages ship (Story 9.1, A-6). On a
// mismatch the needed change belongs to Story 9.1, not to this test or to the
// shipped file.
func TestSystemUnitIsIdenticalToTheShippedUnit(t *testing.T) {
	shipped, err := os.ReadFile(deployUnit)
	if err != nil {
		t.Fatal(err)
	}
	got, err := SystemUnit(DefaultBinary)
	if err != nil {
		t.Fatal(err)
	}
	if got != string(shipped) {
		t.Fatalf("the unit generated by worker up differs from deploy/systemd/minion-worker@.service (owned by Story 9.1);\nrecord the needed change for Story 9.1.\n--- generated ---\n%s\n--- shipped ---\n%s", got, shipped)
	}
}

