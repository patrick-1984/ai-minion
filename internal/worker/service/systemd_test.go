func activeAnswers(state string) func(string) (string, error) {
	return func(line string) (string, error) {
		if strings.Contains(line, "is-active") {
			if state == "active" {
				return "active\n", nil
			}
			return state + "\n", errors.New("exit status 3")
		}
		return "", nil
	}
}

func systemReq(user string) Request {
	return Request{Manager: ManagerSystemd, Scope: ScopeSystem, Binary: "/usr/local/bin/minion", Target: Target{User: user, UID: 1000, GID: 1000, Home: "/home/" + user}}
}

func TestInstallSystemdSystemUnit(t *testing.T) {
	r := &fakeRunner{answer: activeAnswers("active")}
	d := testDeps(t, r)
	var out strings.Builder
	res, err := Install(context.Background(), d, systemReq("ann"), &out)
	if err != nil {
		t.Fatal(err)
	}
	want := []string{
		"systemctl daemon-reload",
		"systemctl enable minion-worker@ann.service",
		"systemctl restart minion-worker@ann.service",
		"systemctl is-active minion-worker@ann.service",
		"systemctl is-active minion-worker@ann.service",
	}
	if got := r.lines(); strings.Join(got, "|") != strings.Join(want, "|") {
		t.Fatalf("commands:\n%s\nwant:\n%s", strings.Join(got, "\n"), strings.Join(want, "\n"))
	}
	unitPath := filepath.Join(d.SystemUnitDir, TemplateUnitName)
	data, err := os.ReadFile(unitPath)
	if err != nil {
		t.Fatal(err)
	}
	// The template never depends on the binary of this install ...
	if exp, _ := SystemUnit(DefaultBinary); string(data) != exp {
		t.Errorf("installed unit differs:\n%s", data)
	}
	// ... the instance's drop-in carries it.
	drop, err := os.ReadFile(filepath.Join(d.SystemUnitDir, "minion-worker@ann.service.d", dropInName))
	if err != nil || !strings.Contains(string(drop), "ExecStart=\nExecStart=/usr/local/bin/minion worker run\n") {
		t.Errorf("drop-in: %v\n%s", err, drop)
	}
	if res.Unit != "minion-worker@ann.service" || res.Path != unitPath || res.Scope != ScopeSystem {
		t.Errorf("result = %+v", res)
	}
	if !strings.Contains(out.String(), "minion-worker@ann.service") {
		t.Errorf("no report: %q", out.String())
	}
}

